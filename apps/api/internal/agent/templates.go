// Render returns the localized message (with the standard intro). Unlocalized entries fall back to English;
// that fallback is listed in docs/assumptions.md and covered by TestTemplatesCoverFiveLanguages.
func Render(key, lang string, params map[string]string) string {
	tpl, ok := templates[key]
	if !ok {
		tpl = templates["clarify.unknown"]
	}
	body := tpl[lang]
	if body == "" {
		body = tpl["en"]
		lang = "en"
	}
	for k, v := range params {
		body = strings.ReplaceAll(body, "{"+k+"}", v)
	}
	i := intro[lang]
	if i == "" {
		i = intro["en"]
	}
	return i + " " + body
}

// TemplateKeys lists known keys (used by tests).
func TemplateKeys() []string {
	out := make([]string, 0, len(templates))
	for k := range templates {
		out = append(out, k)
	}
	return out
}

// FullyLocalized reports whether a key has all five languages.
func FullyLocalized(key string) bool {
	for _, l := range []string{"en", "hi", "te", "ta", "kn"} {
		if templates[key][l] == "" {
			return false
		}
	}
	return true
}

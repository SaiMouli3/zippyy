def line(table: dict[str, dict[str, str]], key: str, lang: str, **kwargs) -> tuple[str, str]:
    """Returns (text, language actually used)."""
    variants = table[key]
    used = lang if lang in variants else "en"
    text = variants[used]
    for k, v in kwargs.items():
        text = text.replace("{" + k + "}", str(v))
    return text, used


def lang_name(code: str, in_lang: str = "en") -> str:
    return LANGUAGE_NAMES_LOCAL.get(in_lang, LANGUAGE_NAMES_LOCAL["en"]).get(code) or LANGUAGE_NAMES_LOCAL["en"].get(code, code)


def fill_template(body: str, params: list[str]) -> str:
    for i, p in enumerate(params, start=1):
        body = body.replace("{{" + str(i) + "}}", p)
    return body
